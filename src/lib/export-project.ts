// ── 可运行工程包导出（P1 收尾）──
// Code 面板里的代码只是"片段"，用户拿到手还要自己搭脚手架。
// 这里把导出的组件代码包成一个 `npm install && npm run dev` 就能跑的
// Vite 工程 zip——"从设计到代码"价值闭环的最后一块。
//
// 纯函数部分（splitReactCss / buildProjectFiles / buildProjectZip）不依赖
// 浏览器 API，可直接被 vitest 单测；只有 downloadProjectZip 触碰 DOM。

import { strToU8, zipSync } from 'fflate'

import type { CodeFramework } from '@/stores/code-output'

/**
 * selectionToCode 的 react 格式把 CSS 以块注释塞在 tsx 末尾：
 *   import './styles.css'
 *   export function X() { ... }
 *   /* styles.css *​/
 *   /​* ...css... *​/
 * 直接跑会报错（styles.css 不存在），这里拆成两个真实文件。
 */
export function splitReactCss(code: string): { tsx: string; css: string } {
  const marker = /\/\*\s*styles\.css\s*\*\//
  const match = code.match(marker)
  if (!match || match.index === undefined) {
    return { tsx: code.trimEnd() + '\n', css: '' }
  }
  const tsx = code.slice(0, match.index).trimEnd() + '\n'
  const rest = code.slice(match.index + match[0].length).trim()
  // rest 形如 /* ...css... */
  const css = rest.replace(/^\/\*/, '').replace(/\*\/\s*$/, '').trim() + '\n'
  return { tsx, css }
}

/** 从导出的 React 代码里取出组件名（App.tsx 要 import 它） */
function reactComponentName(tsx: string): string {
  const m = tsx.match(/export function (\w+)/)
  return m?.[1] ?? 'Component'
}

