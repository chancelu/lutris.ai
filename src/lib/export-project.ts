/**
 * 把单个框架的导出代码组装成可运行 Vite 工程的文件表。
 * HTML 导出本身即是完整页面，无需脚手架，不在此列。
 */
export function buildProjectFiles(
  framework: CodeFramework,
  componentCode: string
): Record<string, string> | null {
  switch (framework) {
    case 'Vue':
      return vueFiles(componentCode)
    case 'React':
      return reactFiles(componentCode)
    default:
      return null
  }
}

export function buildProjectZip(framework: CodeFramework, componentCode: string): Uint8Array | null {
  const files = buildProjectFiles(framework, componentCode)
  if (!files) return null
  const entries: Record<string, Uint8Array> = {}
  for (const [path, content] of Object.entries(files)) {
    entries[path] = strToU8(content)
  }
  return zipSync(entries, { level: 6 })
}

/** 浏览器侧触发 zip 下载；不支持的框架返回 false */
export function downloadProjectZip(framework: CodeFramework, componentCode: string): boolean {
  const zipped = buildProjectZip(framework, componentCode)
  if (!zipped) return false
  const blob = new Blob([zipped.buffer as ArrayBuffer], { type: 'application/zip' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `lutris-${framework.toLowerCase()}-app.zip`
  a.click()
  URL.revokeObjectURL(url)
  return true
}
